const norm = (s: string) => s.toLowerCase().replace(/[׳'"`’״]/g, '').replace(/\s+/g, ' ').trim();

export function findDestination(q: string): Destination | undefined {
  const n = norm(q);
  if (!n) return undefined;
  return DESTINATIONS.find((d) => d.aliases.some((a) => norm(a) === n))
    || DESTINATIONS.find((d) => d.aliases.some((a) => norm(a).includes(n) || (n.length > 3 && n.includes(norm(a)))));
}
