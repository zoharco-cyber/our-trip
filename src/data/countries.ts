export const ANYWHERE = 'בכל מקום';

const norm = (s: string) => s.replace(/['’`]/g, '׳');
/** כל המדינות שהאתגר שייך אליהן. בלי התאמה: "בכל מקום" */
export function countriesOf(text: string): string[] {
  const t = norm(text);
  const hit = COUNTRIES.filter((c) => c.words.some((w) => t.includes(norm(w)))).map((c) => c.name);
  return hit.length ? hit : [ANYWHERE];
}
