const dayNo = (day: string) => Math.floor(new Date(day + 'T12:00:00Z').getTime() / 864e5);
export const wordFor = (day: string) => WORDS[dayNo(day) % WORDS.length];
export const promptFor = (day: string) => PHOTO_PROMPTS[(dayNo(day) * 7) % PHOTO_PROMPTS.length];

/** שבוע לחידון: מספר שבוע ומילים של 7 הימים האחרונים */
export function weekKey(day: string) { return 'w' + Math.floor((dayNo(day) - 3) / 7); }
export function weekWords(day: string) {
  const n = dayNo(day);
  return Array.from({ length: 7 }, (_, i) => WORDS[(n - i) % WORDS.length]);
}
